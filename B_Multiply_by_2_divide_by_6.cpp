void solve() {
    int n;cin>>n;
    int count3=0,count2=0;
    while(n%3==0){
        count3++;
        n/=3;
    }
    while(n%2==0){
        count2++;
        n/=2;
    }
    if(n!=1 or count2>count3){
        cout<<-1<<'\n';
        return;
    }
    cout<<2*count3-count2<<'\n';
}

