void solve() {
    int n;cin>>n;
    int count=0;
    vi v(n);
    for(int i=0;i<n;i++) cin>>v[i];
    for(int i=0;i<n;i++) if(v[i]==0) count++;
    if(count<2) {
        cout<<-1<<'\n';
        return;
    }
    int ans=0;
    if(v[0]==1) ans++;
    if(v[n-1]==1) ans++;
    cout<<ans<<'\n';
}

